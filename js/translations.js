// Sprachverwaltung
class LanguageManager {
    constructor() {
        this.currentLang = this.getInitialLanguage();
    }

    getInitialLanguage() {
        const saved = localStorage.getItem('flagguess-language');
        if (saved && TRANSLATIONS[saved]) return saved;
        
        const browser = navigator.language.split('-')[0];
        return TRANSLATIONS[browser] ? browser : 'de';
    }

    // Interne Methode: Setzt Sprache ohne Page-Update (für Initialisierung)
    setLanguage(lang) {
        if (!TRANSLATIONS[lang]) return;
        this.currentLang = lang;
        localStorage.setItem('flagguess-language', lang);
    }

    // Öffentliche Methode: Wird vom Language Selector aufgerufen
    setLanguageViaSelector(lang) {
        if (!TRANSLATIONS[lang]) return;
        if (lang === this.currentLang) return; // Keine Änderung
        
        this.currentLang = lang;
        localStorage.setItem('flagguess-language', lang);
        
        // Check if we need to navigate to different language folder
        if (window.languageRouter && window.languageRouter.isOnLocalizedPage()) {
            // We're on /de/ or /en/ → navigate to other language version
            window.languageRouter.handleLanguageChange(lang);
            return; // Don't update page, will reload anyway
        }
        
        // We're on root → just update translations
        this.updatePage();
        
        // Update content links if language router exists
        if (window.languageRouter) {
            window.languageRouter.setLanguage(lang);
            window.languageRouter.updateContentLinks();
        }
    }

    get(key) {
        return TRANSLATIONS[this.currentLang][key] || key;
    }

    updatePage() {
        // Datalist aktualisieren
        populateDatalist(this.currentLang);
        
        // UI-Elemente aktualisieren
        this.updateElement('subtitle');
        this.updateElement('attemptLabel', 'attempts');
        this.updateElement('newGameText', 'newGame');
        this.updateElement('guessText', 'guess');
        this.updateElement('playAgainText', 'playAgain');
        this.updateElement('previousGuessesTitle', 'previousGuesses');
        this.updateElement('howToPlayTitle', 'howToPlay');
        this.updateElement('instruction1');
        this.updateElement('instruction2');
        this.updateElement('instruction3');
        this.updateElement('aboutLink');
        this.updateElement('aboutTitle');
        this.updateElement('aboutFeaturesTitle');
        
        // About Modal Description
        const aboutDesc = document.getElementById('aboutDescription');
        if (aboutDesc) aboutDesc.innerHTML = this.get('aboutDescription');
        
        // About Modal Features
        const aboutList = document.querySelector('.about-list');
        if (aboutList) {
            aboutList.innerHTML = `
                <li>${this.get('aboutFeature1')}</li>
                <li>${this.get('aboutFeature2')}</li>
                <li>${this.get('aboutFeature3')}</li>
                <li>${this.get('aboutFeature4')}</li>
            `;
        }
        
        // Input Placeholder
        const input = document.getElementById('countryInput');
        if (input) input.placeholder = this.get('inputPlaceholder');
        
        // Difficulty Select
        const diffSelect = document.getElementById('difficultySelect');
        if (diffSelect) {
            diffSelect.options[0].text = '🟢 ' + (this.currentLang === 'de' ? 'Einfach' : 'Easy');
            diffSelect.options[1].text = '🟡 ' + (this.currentLang === 'de' ? 'Mittel' : 'Medium');
            diffSelect.options[2].text = '🔴 ' + (this.currentLang === 'de' ? 'Schwer' : 'Hard');
        }
        
        // Language Select
        const langSelect = document.getElementById('languageSelect');
        if (langSelect) langSelect.value = this.currentLang;
        
        // Footer Links
        const footerLinks = document.querySelectorAll('.footer-links a');
        if (footerLinks[0]) footerLinks[0].textContent = `🌍 ${this.get('libraryLink')}`;
        if (footerLinks[1]) footerLinks[1].textContent = this.get('aboutLink');
        if (footerLinks[2]) footerLinks[2].textContent = this.get('imprint');
        if (footerLinks[3]) footerLinks[3].textContent = this.get('privacy');
    }

    updateElement(id, key = null) {
        const el = document.getElementById(id);
        if (el) el.textContent = this.get(key || id);
    }
}

// Globale Instanz
let langManager;

document.addEventListener('DOMContentLoaded', () => {
    langManager = new LanguageManager();
    
    // WICHTIG: Initiale Übersetzung beim Laden der Seite
    langManager.updatePage();
    
    // Event Listener für Sprachwechsel
    const langSelect = document.getElementById('languageSelect');
    if (langSelect) {
        langSelect.addEventListener('change', (e) => {
            const newLang = e.target.value;
            langManager.setLanguageViaSelector(newLang);
        });
    }
});
